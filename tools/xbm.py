print("// Generated by tools/xbm.py -- edit the art there, not the bytes here.\n")
for name, art in ART.items():
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16, (name, len(rows))
    out = []
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
        for byte_i in range(2):
            b = 0
            for bit in range(8):
                if r[byte_i * 8 + bit] == "#":
                    b |= 1 << bit
            out.append(b)
    words = ["0x%02x" % b for b in out]
    print(f"pub const {name}: [u8; 32] = [")
    for i in range(0, 32, 8):
        print("    " + ", ".join(words[i:i + 8]) + ",")
    print("];\n")
